"""Build a store's asset set.

    python3 brand/store/build.py              # Google Play -> out/, out.zip
    python3 brand/store/build.py --ios        # App Store   -> out-ios/, out-ios.zip
    python3 brand/store/build.py --ios DIR    # ... somewhere else

Google Play (`out/`):

    01-feature-graphic/          1 x 1024x500
    02-phone/                    8 x 1080x1920   (9:16)
    03-tablet-7in/               8 x 1920x1080   (16:9)
    04-tablet-10in/              8 x 2560x1440   (16:9)
    05-screenshots-min-1080px/   8 x 3840x2160   (16:9)
    06-screenshots-min-720px/    8 x 1280x720    (16:9)
    99-all-screens-phone/       97 x 1080x1920   (every screen in the catalogue)

App Store (`out-ios/`):

    01-iphone-6.5in/            10 x 1284x2778  (portrait)
    02-ipad-12.9in-portrait/    10 x 2048x2732
    03-ipad-12.9in-landscape/   10 x 2732x2048
"""
import os, shutil, sys, zipfile
import catalogue, specs, shot, featured

HERO = ['/dashboard', '/sales/invoice', '/einvoice', '/hr/payroll',
        '/reports', '/ask', '/crm', '/till']

# The App Store slots take ten. The two extra carry the modules the eight
# leave out: what a company owes, and what SSM is waiting for.
HERO_IOS = HERO + ['/purchases/bill', '/secretarial']

PLAY_SETS = [
    ('02-phone', 'phone', (1080, 1920)),
    ('03-tablet-7in', 'tablet7', (1920, 1080)),
    ('04-tablet-10in', 'tablet10', (2560, 1440)),
    ('05-screenshots-min-1080px', 'tablet4k', (3840, 2160)),
    ('06-screenshots-min-720px', 'tablet720', (1280, 720)),
]

IOS_SETS = [
    ('01-iphone-6.5in', 'ios_phone', (1284, 2778)),
    ('02-ipad-12.9in-portrait', 'ios_ipad', (2048, 2732)),
    ('03-ipad-12.9in-landscape', 'ios_ipad_l', (2732, 2048)),
]


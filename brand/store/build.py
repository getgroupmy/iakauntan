STORES = {
    'play': dict(out='out', sets=PLAY_SETS, heroes=HERO, readme=PLAY_README,
                 zip_root='iakauntan-play-assets', feature=True, pool=True),
    'ios': dict(out='out-ios', sets=IOS_SETS, heroes=HERO_IOS, readme=IOS_README,
                zip_root='iakauntan-app-store-assets', feature=False, pool=False),
}


def slug(route):
    return route.strip('/').replace('/', '-') or 'home'


def main(outdir, store='play'):
    s = STORES[store]
    cat = {r: (m, a, l) for m, a, l, r in catalogue.screens()}
    missing = [r for r in s['heroes'] if r not in cat]
    if missing:
        raise SystemExit(f'not in the catalogue any more: {missing}')
    if os.path.isdir(outdir):
        shutil.rmtree(outdir)
    os.makedirs(outdir)

    if s['feature']:
        fg = os.path.join(outdir, '01-feature-graphic')
        os.makedirs(fg)
        featured.build(os.path.join(fg, 'feature-graphic-1024x500.png'))
        print('feature graphic')

    for folder, profile, size in s['sets']:
        path = os.path.join(outdir, folder)
        os.makedirs(path)
        for i, route in enumerate(s['heroes'], 1):
            m, a, l = cat[route]
            img = shot.render(specs.build(m, a, l, route), profile)
            assert img.size == size, (folder, img.size, size)
            img.save(os.path.join(path, f'{i:02d}-{slug(route)}.png'), 'PNG',
                     optimize=True)
        print(f'{folder}: {len(s["heroes"])} x {size[0]}x{size[1]}')

    if s['pool']:
        allp = os.path.join(outdir, '99-all-screens-phone')
        os.makedirs(allp)
        for i, (m, a, l, route) in enumerate(catalogue.screens(), 1):
            img = shot.render(specs.build(m, a, l, route), 'phone')
            img.save(os.path.join(allp, f'{i:03d}-{slug(route)}.png'), 'PNG',
                     optimize=True)
        print(f'99-all-screens-phone: {i} x 1080x1920')

    open(os.path.join(outdir, 'README.txt'), 'w').write(s['readme'])

    zpath = outdir.rstrip('/') + '.zip'
    with zipfile.ZipFile(zpath, 'w', zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(outdir):
            for name in sorted(files):
                full = os.path.join(root, name)
                z.write(full, os.path.join(s['zip_root'],
                                           os.path.relpath(full, outdir)))
    print('zip:', zpath, f'{os.path.getsize(zpath) / 1e6:.1f} MB')
    return zpath


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    store = 'ios' if '--ios' in sys.argv[1:] else 'play'
    here = os.path.dirname(os.path.abspath(__file__))
    main(args[0] if args else os.path.join(here, STORES[store]['out']), store)
